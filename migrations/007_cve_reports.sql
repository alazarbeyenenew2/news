-- CVE reports: users pick technologies (from a catalog or typed in) and a minimum severity, and get an
-- alert for each new CVE that mentions one of them. CVEs are stored as articles (from the NVD and CISA
-- KEV providers) so they reuse the alert queue, retries, digest and "never twice" rules; this table
-- holds their CVE details.
CREATE TABLE cves (
    article_id      BIGINT PRIMARY KEY REFERENCES articles(id) ON DELETE CASCADE,
    cve_id          TEXT NOT NULL UNIQUE,                 -- CVE-2026-1234
    description     TEXT NOT NULL,
    cvss_score      REAL,
    severity        TEXT CHECK (severity IN ('CRITICAL', 'HIGH', 'MEDIUM', 'LOW', 'NONE')),
    cvss_version    TEXT,
    products        JSONB NOT NULL DEFAULT '[]',          -- "vendor product" names, when known
    kev             BOOLEAN NOT NULL DEFAULT FALSE,       -- on CISA's Known Exploited Vulnerabilities list
    kev_date        DATE,
    kev_ransomware  BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL
);

-- Popular technologies people can tick. aliases: the words matched in CVE text.
CREATE TABLE technologies (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key         TEXT NOT NULL UNIQUE,
    name        TEXT NOT NULL,
    grp         TEXT NOT NULL,                            -- group key, e.g. 'web', 'os'
    aliases     JSONB NOT NULL DEFAULT '[]',
    sort_order  INTEGER NOT NULL DEFAULT 0,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL
);

-- A user's technologies: a catalog entry (technology_id set) or their own word (technology_id NULL).
CREATE TABLE user_technologies (
    user_id        BIGINT NOT NULL REFERENCES users(telegram_id) ON DELETE CASCADE,
    term           TEXT NOT NULL,                         -- 'tech:<key>' for catalog entries, else the word
    technology_id  BIGINT REFERENCES technologies(id) ON DELETE CASCADE,
    created_at     TIMESTAMPTZ NOT NULL,                  -- only CVEs found after this are sent for it
    PRIMARY KEY (user_id, term)
);

ALTER TABLE users
    ADD COLUMN cve_alerts BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN cve_enabled_at TIMESTAMPTZ,
    ADD COLUMN cve_all_technologies BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN cve_min_severity TEXT NOT NULL DEFAULT 'HIGH'
        CHECK (cve_min_severity IN ('CRITICAL', 'HIGH', 'MEDIUM', 'ALL'));

-- Which of the user's technologies a CVE alert matched, shown in the alert.
ALTER TABLE notifications ADD COLUMN matched TEXT;
